def sec(heading, first, second, *keys):
    return {"h": heading, "paragraphs": [first, second], "cites": cites(*keys)}


def ladder(title, parties, rows):
    return flow(title, parties, [hop(*row) for row in rows])


def make_lab(title, kind, prompt, steps, question, choices, index, why, cite, **extra):
    row = {
        "title": title,
        "kind": kind,
        "prompt": prompt,
        "steps": steps,
        "check": {
            "q": question,
            "choices": choices,
            "answer": index,
            "why": why,
            "cite": C[cite] if isinstance(cite, str) else cite,
        },
    }
    row.update(extra)
    return row


def make_fault(title, symptom, log, choices, answer, why, cause, fix, *keys):
    return {
        "title": title,
        "symptom": symptom,
        "log": log,
        "choices": choices,
        "answer": answer,
        "why": why,
        "cause": cause,
        "fix": fix,
        "cites": cites(*keys),
    }


def msg(start, headers, body=""):
    return sip(start, headers, body)


