import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const campus = join(root, "campus");

function walk(dir, prefix) {
  const out = {};
  for (const name of readdirSync(dir)) {
    const abs = join(dir, name);
    const rel = `${prefix}/${name}`;
    if (statSync(abs).isDirectory()) Object.assign(out, walk(abs, rel));
    else if (name.endsWith(".json")) out[rel] = JSON.parse(readFileSync(abs, "utf8"));
  }
  return out;
}

const data = walk(join(campus, "data"), "data");
data["downloads/manifest.json"] = JSON.parse(readFileSync(join(campus, "downloads", "manifest.json"), "utf8"));
const body = `/* Generated by scripts/embed_data.mjs. Classic script so file:// can read the catalog. */\nwindow.SIP_DATA=${JSON.stringify(data)};\n`;
writeFileSync(join(campus, "js", "embedded-data.js"), body);
console.log(JSON.stringify({ keys: Object.keys(data).length, bytes: Buffer.byteLength(body) }));
